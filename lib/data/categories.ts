import { orderBy } from "firebase/firestore";
import { makeCrud } from "./crud";
import type { Category } from "./types";

export const categoriesCrud = makeCrud<Omit<Category, "id">>(
  "categories",
  [orderBy("type"), orderBy("sortOrder"), orderBy("name")]
);

